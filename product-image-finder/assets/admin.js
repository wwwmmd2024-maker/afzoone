/* global pifAdmin, jQuery, wp */
(() => {
    'use strict';
    const app = document.querySelector('.pif-search-app');
    if (!app) return;
    const query = document.getElementById('pif-query');
    const results = document.getElementById('pif-results');
    const status = document.getElementById('pif-status');
    const consent = document.getElementById('pif-rights');
    let batch = '';
    let busy = false;
    function message(text, error = false) {
        status.textContent = text;
        status.classList.toggle('is-error', error);
    }
    function toggleBusy(value) {
        busy = value;
        app.setAttribute('aria-busy', String(value));
        app.querySelectorAll('button').forEach(button => {
            button.disabled = value || (button.classList.contains('pif-import') && !consent.checked);
        });
    }
    async function request(action, data) {
        const response = await fetch(pifAdmin.ajaxUrl, {
            method: 'POST', credentials: 'same-origin',
            body: new URLSearchParams({action, nonce: pifAdmin.nonce, post_id: app.dataset.postId, ...data})
        });
        let payload;
        try { payload = await response.json(); } catch (_) { throw new Error('پاسخ سرور خوانده نشد. صفحه را تازه‌سازی کنید و دوباره تلاش کنید.'); }
        if (!response.ok || !payload.success) {
            throw new Error(payload.data?.message || 'درخواست ناموفق بود؛ صفحه را تازه‌سازی و لایسنس را بررسی کنید.');
        }
        return payload.data;
    }
    function externalLink(text, href) {
        const link = document.createElement('a');
        link.textContent = text;
        link.href = href;
        link.target = '_blank';
        link.rel = 'noopener noreferrer';
        return link;
    }
    function updateProduct(data, mode) {
        if (mode === 'featured') {
            // HTML is generated by WordPress, not by the external search provider.
            const featured = document.querySelector('#postimagediv .inside');
            if (featured) jQuery(featured).html(data.featured_html);
            if (window.wp?.data) {
                const editor = wp.data.dispatch('core/editor');
                if (editor?.editPost) editor.editPost({featured_media: data.attachment_id});
            }
        } else {
            const field = document.getElementById('product_image_gallery');
            const list = document.querySelector('#product_images_container ul.product_images');
            if (field && list) {
                // Preserve unsaved gallery edits in the currently open WooCommerce editor.
                const ids = field.value.split(',').filter(Boolean);
                const id = String(data.attachment_id);
                if (!ids.includes(id)) ids.push(id);
                field.value = ids.join(',');
                if (!list.querySelector(`[data-attachment_id="${Number(data.attachment_id)}"]`)) {
                    const item = document.createElement('li');
                    item.className = 'image'; item.dataset.attachment_id = id;
                    const image = document.createElement('img'); image.src = data.thumbnail; image.alt = '';
                    const actions = document.createElement('ul'); actions.className = 'actions';
                    const li = document.createElement('li');
                    const remove = document.createElement('a');
                    remove.href = '#'; remove.className = 'delete tips'; remove.dataset.tip = 'حذف تصویر'; remove.textContent = 'حذف';
                    li.append(remove); actions.append(li); item.append(image, actions); list.append(item);
                }
                jQuery(field).trigger('change');
            }
        }
        jQuery(document.body).trigger('pif_image_imported', [data, mode]);
    }
    function render(items) {
        results.replaceChildren();
        for (const item of items) {
            const card = document.createElement('article'); card.className = 'pif-image-card';
            const image = document.createElement('img');
            image.src = item.thumb; image.alt = item.title; image.loading = 'lazy'; image.referrerPolicy = 'no-referrer';
            image.addEventListener('error', () => { image.alt = 'پیش‌نمایش در دسترس نیست؛ منبع را باز کنید.'; });
            const content = document.createElement('div'); content.className = 'pif-card-content';
            const heading = document.createElement('h4'); heading.textContent = item.title;
            const details = document.createElement('p'); details.className = 'pif-image-detail';
            details.textContent = `${item.width || '?'} × ${item.height || '?'} · ${item.license}`;
            const credit = document.createElement('p'); credit.className = 'pif-image-credit'; credit.textContent = item.artist;
            const links = document.createElement('div'); links.className = 'pif-source-links';
            links.append(externalLink('مشاهده منبع ↗', item.source));
            if (item.license_url) links.append(externalLink('مجوز ↗', item.license_url));
            const actions = document.createElement('div'); actions.className = 'pif-card-actions';
            for (const [mode, text] of [['featured', 'تصویر شاخص'], ['gallery', 'افزودن به گالری']]) {
                const button = document.createElement('button');
                button.type = 'button'; button.className = 'button pif-import';
                button.textContent = text; button.disabled = !consent.checked;
                button.addEventListener('click', async () => {
                    if (busy || !consent.checked) return;
                    if (mode === 'featured' && document.querySelector('#postimagediv img') && !window.confirm('تصویر شاخص فعلی جایگزین شود؟ تصویر قبلی از کتابخانه حذف نمی‌شود.')) return;
                    toggleBusy(true); message('در حال دریافت و ثبت تصویر… لطفاً این صفحه را نبندید.');
                    try {
                        const data = await request('pif_import', {batch, image_id: item.id, mode, rights_confirmed: '1'});
                        updateProduct(data, mode); message(data.message);
                        card.classList.add('is-imported');
                    } catch (error) { message(error.message || 'خطای ارتباط با سرور.', true); }
                    finally { toggleBusy(false); }
                });
                actions.append(button);
            }
            content.append(heading, details, credit, links, actions); card.append(image, content); results.append(card);
        }
    }
    async function search() {
        if (busy) return;
        const value = query.value.trim();
        if (value.length < 2) { message('نام محصول را وارد کنید.', true); query.focus(); return; }
        toggleBusy(true); message('در حال جست‌وجوی تصویر…'); results.replaceChildren(); consent.checked = false;
        try {
            const data = await request('pif_search', {query: value}); batch = data.batch; render(data.items);
            message(data.items.length ? `${data.items.length} تصویر پیدا شد. مدل محصول، منبع و مجوز را بررسی کنید.` : 'تصویری پیدا نشد؛ مدل دقیق یا نام انگلیسی را امتحان کنید، یا منبع جست‌وجو را تغییر دهید.');
        } catch (error) { message(error.message || 'خطای ارتباط با سرور.', true); }
        finally { toggleBusy(false); }
    }
    document.getElementById('pif-search').addEventListener('click', search);
    query.addEventListener('keydown', event => { if (event.key === 'Enter') { event.preventDefault(); search(); } });
    document.getElementById('pif-use-title').addEventListener('click', () => {
        const title = document.getElementById('title');
        let value = title?.value || '';
        if (!value && window.wp?.data) value = wp.data.select('core/editor')?.getEditedPostAttribute('title') || '';
        query.value = value; query.focus();
    });
    consent.addEventListener('change', () => toggleBusy(busy));
})();
